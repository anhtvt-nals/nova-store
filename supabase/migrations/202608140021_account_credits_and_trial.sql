create table if not exists public.credit_wallets (
  profile_id bigint primary key references public.profiles(id) on delete cascade,
  balance numeric(18,2) not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.credit_ledger (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete restrict,
  amount numeric(18,2) not null check (amount <> 0),
  balance_after numeric(18,2) not null check (balance_after >= 0),
  type text not null check (type in ('trial_grant','admin_grant','admin_adjustment','order_debit','refund')),
  reference text unique,
  note text not null default '',
  created_by_profile_id bigint references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists credit_ledger_profile_created_idx on public.credit_ledger(profile_id, created_at desc);

