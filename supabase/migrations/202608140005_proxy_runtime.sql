-- Runtime control-plane for dynamically provisioned proxy nodes.
-- Supabase is the durable source of truth; Nest SSE reads proxy_node_events.

alter table public.proxy_providers
  add column max_sandboxes integer check (max_sandboxes is null or max_sandboxes > 0),
  add column reserved_replacement_slots integer not null default 1 check (reserved_replacement_slots >= 0),
  add column max_concurrent_provisions integer not null default 2 check (max_concurrent_provisions > 0);

alter table public.provider_api_keys
  add column max_sandboxes integer check (max_sandboxes is null or max_sandboxes > 0);

create table public.proxy_nodes (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  provider_id bigint references public.proxy_providers(id) on delete set null,
  provider_api_key_id bigint references public.provider_api_keys(id) on delete set null,
  status text not null default 'queued' check (status in (
    'queued', 'provisioning', 'online', 'rotating', 'degraded', 'offline',
    'error', 'expired', 'terminating', 'terminated'
  )),
  public_host text,
  tunnel_port integer check (tunnel_port is null or tunnel_port between 1 and 65535),
  egress_ip inet,
  current_instance_id text,
  last_health_at timestamptz,
  last_status_change_at timestamptz not null default now(),
  next_rotation_at timestamptz,
  expires_at timestamptz,
  error_code text,
  error_message text,
  health jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.proxy_node_instances (
  id bigint generated by default as identity primary key,
  node_id bigint not null references public.proxy_nodes(id) on delete cascade,
  provider_id bigint not null references public.proxy_providers(id) on delete restrict,
  provider_api_key_id bigint references public.provider_api_keys(id) on delete set null,
  external_instance_id text not null,
  status text not null default 'provisioning' check (status in (
    'provisioning', 'running', 'stopping', 'stopped', 'error'
  )),
  started_at timestamptz,
  stopped_at timestamptz,
  expires_at timestamptz,
  last_heartbeat_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(provider_id, external_instance_id)
);

create table public.proxy_node_events (
  id bigint generated by default as identity primary key,
  node_id bigint not null references public.proxy_nodes(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index proxy_nodes_profile_status_idx on public.proxy_nodes(profile_id, status);
create index proxy_nodes_provider_status_idx on public.proxy_nodes(provider_id, status);
create index proxy_node_instances_node_created_idx on public.proxy_node_instances(node_id, created_at desc);
create index proxy_node_events_profile_id_idx on public.proxy_node_events(profile_id, id);

