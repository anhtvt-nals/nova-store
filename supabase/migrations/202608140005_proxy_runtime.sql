-- Preserve existing active resource-backed orders as runtime nodes. New worker
-- callbacks can progressively take ownership of these rows.
insert into public.proxy_nodes(
  order_id, profile_id, provider_id, status, public_host, tunnel_port, egress_ip,
  last_health_at, next_rotation_at, expires_at, metadata
)
select
  o.id,
  o.profile_id,
  r.provider_id,
  case when r.status = 'online' then 'online' else 'offline' end,
  nullif(r.secrets ->> 'host', ''),
  case when (r.secrets ->> 'port') ~ '^[0-9]+$' then (r.secrets ->> 'port')::integer else null end,
  case when coalesce(r.health ->> 'egressIp', '') <> '' then (r.health ->> 'egressIp')::inet else null end,
  case when r.status = 'online' then now() else null end,
  case
    when o.activated_at is not null then o.activated_at + interval '60 minutes'
    else null
  end,
  o.expires_at,
  jsonb_build_object('migratedFromResourceId', r.id)
from public.orders o
join public.resources r on r.id = o.resource_id
where o.status = 'active'
on conflict (order_id) do nothing;

-- Active orders automatically receive one logical node. Provisioning remains
-- asynchronous and moves queued -> provisioning -> online.
create or replace function public.ensure_proxy_node_for_active_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  resource_row public.resources%rowtype;
  new_node_id bigint;
begin
  if new.status = 'active' and old.status is distinct from new.status then
    if new.resource_id is not null then
      select * into resource_row from public.resources where id = new.resource_id;
    end if;

    insert into public.proxy_nodes(
      order_id, profile_id, provider_id, status, public_host, tunnel_port,
      next_rotation_at, expires_at, metadata
    ) values (
      new.id,
      new.profile_id,
      resource_row.provider_id,
      'queued',
      nullif(resource_row.secrets ->> 'host', ''),
      case when (resource_row.secrets ->> 'port') ~ '^[0-9]+$' then (resource_row.secrets ->> 'port')::integer else null end,
      coalesce(new.activated_at, now()) + interval '60 minutes',
      new.expires_at,
      case when new.resource_id is null then '{}'::jsonb else jsonb_build_object('resourceId', new.resource_id) end
    )
    on conflict (order_id) do update set
      expires_at = excluded.expires_at,
      updated_at = now()
    returning id into new_node_id;

    insert into public.proxy_node_events(node_id, profile_id, event_type, payload)
    values (new_node_id, new.profile_id, 'proxy.node.queued', jsonb_build_object('status', 'queued'));
  end if;
  return new;
end;
$$;

create trigger orders_create_proxy_node
after update of status on public.orders
for each row execute function public.ensure_proxy_node_for_active_order();

-- Worker-facing atomic update: status and its SSE event are committed together.
create or replace function public.report_proxy_node_status(
  target_node_id bigint,
  next_status text,
  reported_instance_id text default null,
  reported_egress_ip text default null,
  reported_public_host text default null,
  reported_tunnel_port integer default null,
  reported_next_rotation_at timestamptz default null,
  reported_health jsonb default '{}'::jsonb,
  reported_error_code text default null,
  reported_error_message text default null
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  target_node public.proxy_nodes%rowtype;
  new_event_id bigint;
begin
  if next_status not in (
    'queued', 'provisioning', 'online', 'rotating', 'degraded', 'offline',
    'error', 'expired', 'terminating', 'terminated'
  ) then raise exception 'Unsupported proxy node status'; end if;

  select * into target_node from public.proxy_nodes where id = target_node_id for update;
  if not found then raise exception 'Proxy node not found'; end if;

  update public.proxy_nodes set
    status = next_status,
    current_instance_id = coalesce(reported_instance_id, current_instance_id),
    egress_ip = case when reported_egress_ip is null then egress_ip else reported_egress_ip::inet end,
    public_host = coalesce(reported_public_host, public_host),
    tunnel_port = coalesce(reported_tunnel_port, tunnel_port),
    next_rotation_at = coalesce(reported_next_rotation_at, next_rotation_at),
    last_health_at = case when next_status in ('online', 'rotating') then now() else last_health_at end,
    last_status_change_at = case when status is distinct from next_status then now() else last_status_change_at end,
    health = coalesce(reported_health, '{}'::jsonb),
    error_code = reported_error_code,
    error_message = reported_error_message
  where id = target_node_id;

  insert into public.proxy_node_events(node_id, profile_id, event_type, payload)
  values (
    target_node_id,
    target_node.profile_id,
    'proxy.node.status',
    jsonb_strip_nulls(jsonb_build_object(
      'nodeId', target_node_id,
      'status', next_status,
      'instanceId', reported_instance_id,
      'egressIp', reported_egress_ip,
      'publicHost', reported_public_host,
      'tunnelPort', reported_tunnel_port,
      'nextRotationAt', reported_next_rotation_at,
      'errorCode', reported_error_code,
      'errorMessage', reported_error_message
    ))
  ) returning id into new_event_id;

  return new_event_id;
end;
$$;

