create table public.static_residential_proxies (
  id bigint generated by default as identity primary key,
  label text,
  host text not null,
  port integer not null check (port between 1 and 65535),
  username text not null,
  password_ciphertext text not null,
  password_iv text not null,
  password_tag text not null,
  status text not null default 'available' check (status in ('available','assigned','disabled')),
  assigned_order_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(host, port, username)
);

create table public.static_residential_orders (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete restrict,
  status text not null default 'active' check (status in ('active','quota_exceeded','expired','suspended','cancelled')),
  node_count integer not null default 5 check (node_count = 5),
  quota_bytes bigint not null default 5368709120 check (quota_bytes = 5368709120),
  used_bytes bigint not null default 0 check (used_bytes >= 0),
  price_per_gb_day numeric(18,4) not null check (price_per_gb_day >= 0),
  amount numeric(18,4) not null check (amount >= 0),
  credit_cost numeric(18,4) not null check (credit_cost >= 0),
  activated_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.static_residential_proxies add constraint static_residential_proxies_order_fk foreign key (assigned_order_id) references public.static_residential_orders(id) on delete set null;

create table public.static_residential_nodes (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.static_residential_orders(id) on delete cascade,
  upstream_proxy_id bigint not null references public.static_residential_proxies(id) on delete restrict,
  public_port integer not null unique check (public_port between 10000 and 20000),
  service_name text not null unique,
  status text not null default 'active' check (status in ('active','suspended','expired','quota_exceeded')),
  next_upstream_rotation_at timestamptz not null default now() + interval '1 hour',
  last_upstream_rotation_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index static_residential_orders_profile_idx on public.static_residential_orders(profile_id, created_at desc);
create index static_residential_nodes_order_idx on public.static_residential_nodes(order_id);
create index static_residential_nodes_rotation_idx on public.static_residential_nodes(next_upstream_rotation_at) where status = 'active';
create unique index static_residential_nodes_active_upstream_idx on public.static_residential_nodes(upstream_proxy_id) where status = 'active';

